def get_text(key, lang="pt_PT"):
    """
    Retrieves the localized text for a given translation key.
    Falls back to English or key name if language or key is missing.
    """
    if key in TRANSLATIONS:
        lang_dict = TRANSLATIONS[key]
        if lang in lang_dict:
            return lang_dict[lang]
        elif "en" in lang_dict:
            return lang_dict["en"]
    return key
